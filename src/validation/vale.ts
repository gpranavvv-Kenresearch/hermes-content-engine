import type { BrandConfig } from '../schemas/index.js';

/**
 * Generates Vale (https://vale.sh) style files from the brand config, so the
 * editor/CI linter and the in-process validator share one source of truth.
 * Pure: returns { relativePath: contents }. scripts/gen-vale-styles.ts writes
 * them to disk; a test regenerates them and compares with the committed files.
 * Vale itself is NOT a dependency.
 */

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;

function rule(lines: string[]): string {
  return lines.join('\n') + '\n';
}

export function generateValeFiles(brand: BrandConfig): Record<string, string> {
  const files: Record<string, string> = {};

  files['.vale.ini'] = rule([
    '# GENERATED by scripts/gen-vale-styles.ts from src/config/brand.config.ts. Do not edit by hand.',
    'StylesPath = styles',
    'MinAlertLevel = suggestion',
    '',
    '[*.md]',
    'BasedOnStyles = KenResearch',
  ]);

  files['styles/KenResearch/BannedPhrases.yml'] = rule([
    '# GENERATED. Source: brandConfig.bannedPhrases',
    'extends: existence',
    `message: ${q("Banned phrase '%s'. Rephrase in a plain analyst voice.")}`,
    'level: error',
    'ignorecase: true',
    'tokens:',
    ...brand.bannedPhrases.map((p) => `  - ${q(p.replace(/’/g, "'"))}`),
  ]);

  files['styles/KenResearch/HypeWords.yml'] = rule([
    '# GENERATED. Source: brandConfig.bannedPromoWords',
    'extends: existence',
    `message: ${q("Hype word '%s'. State the evidence instead.")}`,
    'level: warning',
    'ignorecase: true',
    'tokens:',
    ...brand.bannedPromoWords.map((w) => `  - ${q(w)}`),
  ]);

  files['styles/KenResearch/EmDash.yml'] = rule([
    '# GENERATED. Source: brandConfig.bannedCharacters',
    'extends: existence',
    `message: ${q('Em/en dashes are not allowed. Use a comma, colon or hyphen.')}`,
    'level: error',
    'nonword: true',
    'tokens:',
    ...brand.bannedCharacters.map((c) => `  - ${q(c)}`),
  ]);

  files['styles/KenResearch/WeOur.yml'] = rule([
    '# GENERATED. Ken Research is written about in the third person.',
    'extends: existence',
    `message: ${q("Avoid first person '%s'. Write 'Ken Research finds ...' instead.")}`,
    'level: warning',
    'ignorecase: true',
    'tokens:',
    '  - we',
    '  - our',
    '  - ours',
  ]);

  return files;
}
